#!/usr/bin/env bash
# nginx variables are written literally below, so single quotes are meant
# shellcheck disable=SC2016
# prints the Nginx file that tells the proxy which origins may read its own error answers
# (429, 413, 502 and 504). It is generated from ALLOWED_ORIGINS and CREDENTIALED_ORIGINS in
# backend/.env, the two settings the API's CORS reads (backend/app/config.py and cors.py), so an
# origin is changed in one place and the two cannot drift. The rules match the app's:
#   - ALLOWED_ORIGINS is a comma separated list of origins
#   - CREDENTIALED_ORIGINS, when set, are the origins that may send cookies. When it is empty
#     the first of ALLOWED_ORIGINS is the only one, as in the app
# an origin must be scheme://host[:port] and nothing else. A wildcard, "null" or a path is
# refused, so this file can never allow every origin.
#
#   bash infra/scripts/render-cors.sh | sudo tee /etc/nginx/phaemos-cors-origins.conf   (as root: Section 9)
#
# check-nginx.sh renders it again on every deploy and fails when the installed file differs.
set -euo pipefail

# shellcheck source=lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

[ -f "${ENV_FILE}" ] || { echo "missing ${ENV_FILE}" >&2; exit 1; }

allowed="$(env_value ALLOWED_ORIGINS)"
credentialed="$(env_value CREDENTIALED_ORIGINS)"

split_origins() {
    local item
    # shellcheck disable=SC2086
    IFS=',' read -r -a parts <<< "$1"
    for item in "${parts[@]}"; do
        item="${item#"${item%%[![:space:]]*}"}"
        item="${item%"${item##*[![:space:]]}"}"
        [ -n "${item}" ] && printf '%s\n' "${item}"
    done
    return 0
}

mapfile -t origins < <(split_origins "${allowed}")
if [ -n "${credentialed}" ]; then
    mapfile -t creds < <(split_origins "${credentialed}")
else
    creds=("${origins[@]:0:1}")
fi

valid() {
    [[ "$1" =~ ^https?://[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?(:[0-9]{1,5})?$ ]]
}
for origin in "${origins[@]}" "${creds[@]}"; do
    [ -z "${origin}" ] && continue
    valid "${origin}" || { echo "not an origin (scheme://host[:port], no wildcard): ${origin}" >&2; exit 1; }
done

echo "# generated by infra/scripts/render-cors.sh from ALLOWED_ORIGINS and CREDENTIALED_ORIGINS in"
echo "# backend/.env. Do not edit: change those settings and render again."
echo 'map $http_origin $phaemos_cors_origin {'
echo '    default "";'
for origin in $(printf '%s\n' "${origins[@]}" "${creds[@]}" | sort -u); do
    [ -n "${origin}" ] && printf '    "%s" $http_origin;\n' "${origin}"
done
echo '}'
echo 'map $http_origin $phaemos_cors_credentials {'
echo '    default "";'
for origin in $(printf '%s\n' "${creds[@]}" | sort -u); do
    [ -n "${origin}" ] && printf '    "%s" "true";\n' "${origin}"
done
echo '}'
# the headers a page may read are listed only for an origin that is allowed. The same list as
# the API's (EXPOSED_HEADERS in backend/app/cors.py) as far as an Nginx answer carries them
echo 'map $http_origin $phaemos_cors_expose {'
echo '    default "";'
for origin in $(printf '%s\n' "${origins[@]}" "${creds[@]}" | sort -u); do
    [ -n "${origin}" ] && printf '    "%s" "X-Total-Count, Date, X-Request-ID, Retry-After";\n' "${origin}"
done
echo '}'
