#!/usr/bin/env bash
# regenerates backend/requirements.lock from backend/requirements.txt: every package, direct
# and indirect, pinned with the hashes of its release files. The production image installs
# the lock with pip's --require-hashes, so a file that is not the one recorded here is refused
# at build time. Run it on a developer machine, after any change to requirements.txt and
# commit the result.
#
#   bash infra/scripts/lock-requirements.sh            write the lock
#   bash infra/scripts/lock-requirements.sh --check    write nothing: fail when the lock is out of date
#
# --check is what CI runs. It resolves again with the committed lock as the starting point, so
# every pin that still satisfies requirements.txt is kept and a release published since does not
# count as drift. It fails only when requirements.txt asks for something the lock does not hold
# (a new package, a changed version, a removed line).
#
# it runs pip-tools in a throwaway container made from the same pinned Python image that the
# dockerfile builds on, so the lock is resolved for the Python the image really has. The
# container reaches the package index to read the hashes: that is the one step that needs the
# network. Nothing from backend/ is run.
set -euo pipefail

mode="write"
case "${1:-}" in
    "") ;;
    --check) mode="check" ;;
    *)
        echo "usage: bash infra/scripts/lock-requirements.sh [--check]" >&2
        exit 1
        ;;
esac

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
BACKEND="${REPO_DIR}/backend"

image="$(sed -n 's/^FROM \(python:[^ ]*\).*/\1/p' "${BACKEND}/Dockerfile" | head -n 1)"
if ! [[ "${image}" =~ ^python:[0-9.]+-slim@sha256:[0-9a-f]{64}$ ]]; then
    echo "the Dockerfile's FROM line is not the pinned python image: ${image:-none}" >&2
    exit 1
fi

work="$(mktemp -d)"
trap 'rm -rf "${work}"' EXIT
cp "${BACKEND}/requirements.txt" "${work}/requirements.txt"
if [ "${mode}" = "check" ]; then
    # pip-compile keeps the pins it finds in an existing output file
    cp "${BACKEND}/requirements.lock" "${work}/requirements.lock"
fi

docker run --rm -v "${work}:/w" -w /w "${image}" sh -c '
    pip install -q --root-user-action=ignore pip-tools==7.7.0 &&
    pip-compile --quiet --generate-hashes --strip-extras --no-header --allow-unsafe -o requirements.lock requirements.txt'

if [ "${mode}" = "check" ]; then
    # comments (the header and the "via" notes) are not part of what pip installs
    if diff <(grep -vE '^[[:space:]]*#' "${BACKEND}/requirements.lock") <(grep -vE '^[[:space:]]*#' "${work}/requirements.lock") > /dev/null; then
        echo "backend/requirements.lock is up to date"
        exit 0
    fi
    echo "backend/requirements.lock is out of date: run bash infra/scripts/lock-requirements.sh and commit the result" >&2
    diff <(grep -vE '^[[:space:]]*#' "${BACKEND}/requirements.lock") <(grep -vE '^[[:space:]]*#' "${work}/requirements.lock") | head -40 >&2 || true
    exit 1
fi

{
    printf '# generated by infra/scripts/lock-requirements.sh from requirements.txt. Do not edit by hand.\n'
    printf '# every package, direct and indirect, is pinned with the hashes of its release files and\n'
    printf '# the production image installs it with --require-hashes, so a changed or substituted file\n'
    printf '# is refused at build time.\n'
    cat "${work}/requirements.lock"
} > "${BACKEND}/requirements.lock"
echo "wrote ${BACKEND}/requirements.lock"
