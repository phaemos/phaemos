"""
Write the OpenAPI document and the table of routes, with no database and no running server.

    python -m app.scripts.export_openapi ../docs/openapi.json ../docs/api-routes.md

`make openapi` runs it. The environment is set to harmless development values before the app is imported, so nothing needs
configuring and nothing is contacted. The demo routes (development only) are left out, because production does not serve them.
The output is sorted and has no date, so a change shows in review as a diff and CI can fail when the committed copy is stale.
"""

import json
import os
import sys

# placeholders only. They are never used to sign or connect to anything: the app is imported and its schema read
os.environ.setdefault("DATABASE_URL", "postgresql://placeholder:placeholder@localhost:5432/placeholder")
os.environ.setdefault("SECRET_KEY", "openapi-export-placeholder-not-used-for-anything")
os.environ["ENVIRONMENT"] = "development"
os.environ.setdefault("RELEASE_VERSION", "unreleased")


def route_table(app) -> str:
    from app.config import settings
    from app.limiter import _has_own_limit, limiter
    from app.services import token_access

    default_limits = {
        token_access.PUBLIC: f"{settings.rate_limit_anonymous} per address",
        token_access.TOKEN: f"{settings.rate_limit_signed_in} per account",
        token_access.SESSION_ONLY: f"{settings.rate_limit_signed_in} per account",
        token_access.DEVICE_KEY: "its own allowance, per device key",
    }
    rows = []
    for route in token_access.iter_routes(app):
        if not route.include_in_schema or route.path_format.startswith("/api/v1/demo"):
            continue
        for method in sorted((getattr(route, "methods", None) or set()) - {"HEAD", "OPTIONS"}):
            kind = token_access.classify(route, method)
            own = ""
            if _has_own_limit(route):
                limits = limiter._route_limits.get(f"{route.endpoint.__module__}.{route.endpoint.__name__}", [])
                own = ", ".join(sorted({str(item.limit) for item in limits}))
            limit = own or default_limits.get(kind.kind, "")
            rows.append((route.path_format, method, kind.kind, kind.least_scope or "", limit, "deprecated alias" if route.deprecated else ""))
    lines = [
        "# Routes by class, scope and limit",
        "",
        "Generated by `make openapi` from the code. Do not edit it by hand.",
        "",
        "| Method | Path | Class | Least scope | Limit | Note |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    lines += [f"| {m} | `{p}` | {k} | {s or '-'} | {limit} | {note or '-'} |" for p, m, k, s, limit, note in sorted(rows)]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) < 2:
        print("usage: python -m app.scripts.export_openapi OPENAPI.json [ROUTES.md]", file=sys.stderr)
        return 2
    from app.main import app

    document = app.openapi()
    document["paths"] = {path: ops for path, ops in document["paths"].items() if not path.startswith("/api/v1/demo")}
    with open(argv[1], "w") as handle:
        json.dump(document, handle, indent=2, sort_keys=True)
        handle.write("\n")
    if len(argv) > 2:
        with open(argv[2], "w") as handle:
            handle.write(route_table(app))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
