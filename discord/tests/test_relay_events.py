def stated(name):
    """The new fixtures say what they expect in their names. Held and skipped ones post nothing."""
    if name.endswith(("_held", "_skipped", "_fails")):
        return 0
    if name.endswith("_posted"):
        return 1
    return None


EXPECTED_EXIT = {
    "issue_labeled_forbidden_token_fails": 1,
    "issue_labeled_server_error_fails": 1,
}


def test_every_fixture_has_a_golden_file_and_a_stated_expectation():
    names = {path.stem for path in EVENTS}
    assert len(names) >= 90
    if not os.environ.get("RELAY_UPDATE_GOLDEN"):
        assert names == {path.stem for path in GOLDEN.glob("*.json")}
    for name in names:
        if name.startswith("hostile_"):
            continue
        assert name in EXPECTED_POST_COUNT or name in MUST_POST_NOTHING or stated(name) is not None, name


@pytest.mark.parametrize("path", EVENTS, ids=lambda p: p.stem)
def test_event_produces_the_golden_posts(path, receiver, tmp_path):
    recorded = json.loads(path.read_text())
    extra = api_env(recorded, receiver)
    run = run_relay(tmp_path, recorded["event_name"], recorded["payload"], receiver, extra_env=extra)
    actual = {"exit": run.code, "posts": receiver.posts()}
    calls = [r["path"] for r in receiver.requests if r.get("method") == "GET"]
    if calls:
        actual["api_calls"] = calls
    if not actual["posts"]:
        line = [item for item in run.out.splitlines() if "nothing to post" in item or "::error" in item]
        actual["note"] = line[0].removeprefix("relay: ") if line else ""
    golden_file = GOLDEN / path.name
    if os.environ.get("RELAY_UPDATE_GOLDEN"):
        golden_file.write_text(json.dumps(actual, indent=2, ensure_ascii=True) + "\n")
    expected = json.loads(golden_file.read_text())
    assert actual == expected
    assert run.code == EXPECTED_EXIT.get(path.stem, 0)
    if stated(path.stem) is not None:
        assert len(actual["posts"]) == stated(path.stem)
    if path.stem in EXPECTED_POST_COUNT:
        assert len(actual["posts"]) == EXPECTED_POST_COUNT[path.stem]
    if path.stem in MUST_POST_NOTHING:
        assert actual["posts"] == []
        assert receiver.requests == []


@pytest.mark.parametrize("path", EVENTS, ids=lambda p: p.stem)
def test_every_post_follows_the_form_in_the_specification(path, receiver, tmp_path):
    recorded = json.loads(path.read_text())
    run_relay(tmp_path, recorded["event_name"], recorded["payload"], receiver, extra_env=api_env(recorded, receiver))
    for post in receiver.posts():
        payload = post["payload"]
        assert post["query"] == "wait=true"
        assert payload["allowed_mentions"] == {"parse": []}
        assert len(payload["content"]) <= 2000
        assert len(payload["username"]) <= 80
        if post["secret"] == "DISCORD_WEBHOOK_FEED":
            assert payload["flags"] == 4096
            assert "embeds" not in payload
            assert payload["content"].endswith(">") or ">" in payload["content"]
        else:
            assert payload["flags"] == 0
            assert len(payload["embeds"]) == 1
            embed = payload["embeds"][0]
            assert len(embed["title"]) <= 256
            assert len(embed["description"]) <= 3800
            assert embed["color"] == 2450411
            assert "author" not in embed and "thumbnail" not in embed and "image" not in embed
        assert "avatar_url" not in payload
